-- YouTube 账号 / 视频 / 发布任务 / 评论 / 评论回复任务
-- 字段对齐 YouTube Data API v3（OAuth2 + videos / commentThreads / comments）

CREATE TABLE IF NOT EXISTS `youtube_accounts` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `owner_id` INT NOT NULL DEFAULT 0 COMMENT '归属运营用户 admin_users.id',
  `username` VARCHAR(191) NOT NULL DEFAULT '' COMMENT '登录邮箱或频道句柄',
  `password` VARCHAR(255) NOT NULL DEFAULT '' COMMENT '账号密码（本地保管，API 以 OAuth 为准）',
  `nickname` VARCHAR(191) NOT NULL DEFAULT '' COMMENT '显示昵称',
  `channel_id` VARCHAR(64) NOT NULL DEFAULT '' COMMENT 'YouTube channelId (UC...)',
  `channel_title` VARCHAR(255) NOT NULL DEFAULT '',
  `channel_custom_url` VARCHAR(191) NOT NULL DEFAULT '' COMMENT '自定义 URL / @handle',
  `google_cloud_project_id` VARCHAR(128) NOT NULL DEFAULT '' COMMENT 'Google Cloud 项目 ID',
  `api_key` VARCHAR(255) NOT NULL DEFAULT '' COMMENT 'API Key（只读接口可选）',
  `oauth_client_id` VARCHAR(255) NOT NULL DEFAULT '' COMMENT 'OAuth 2.0 Client ID',
  `oauth_client_secret` VARCHAR(255) NOT NULL DEFAULT '' COMMENT 'OAuth 2.0 Client Secret',
  `oauth_redirect_uri` VARCHAR(500) NOT NULL DEFAULT '' COMMENT '授权回调地址',
  `oauth_scopes` TEXT NULL COMMENT '授权 scope，空格或换行分隔',
  `access_token` TEXT NULL COMMENT '当前 access_token',
  `refresh_token` TEXT NULL COMMENT 'refresh_token',
  `token_type` VARCHAR(32) NOT NULL DEFAULT 'Bearer',
  `token_expires_at` DATETIME NULL COMMENT 'access_token 过期时间',
  `last_login_at` DATETIME NULL COMMENT '最近登录/授权成功时间',
  `status` VARCHAR(32) NOT NULL DEFAULT 'enabled' COMMENT 'enabled|disabled|expired|error',
  `last_error` VARCHAR(500) NOT NULL DEFAULT '',
  `extra_json` JSON NULL COMMENT '扩展配置（quota、默认隐私等）',
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_yt_acc_owner` (`owner_id`),
  KEY `idx_yt_acc_channel` (`channel_id`),
  KEY `idx_yt_acc_username` (`username`),
  KEY `idx_yt_acc_status` (`status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='YouTube 账号与 Google API 开发者配置';

CREATE TABLE IF NOT EXISTS `youtube_videos` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `owner_id` INT NOT NULL DEFAULT 0,
  `account_id` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'youtube_accounts.id',
  `youtube_video_id` VARCHAR(64) NOT NULL DEFAULT '' COMMENT '平台 videoId',
  `channel_id` VARCHAR(64) NOT NULL DEFAULT '',
  `title` VARCHAR(255) NOT NULL DEFAULT '',
  `description` MEDIUMTEXT NULL,
  `tags_json` JSON NULL COMMENT '标签数组',
  `category_id` VARCHAR(32) NOT NULL DEFAULT '' COMMENT 'snippet.categoryId',
  `privacy_status` VARCHAR(32) NOT NULL DEFAULT 'private' COMMENT 'public|unlisted|private',
  `publish_at` DATETIME NULL COMMENT '定时公开 status.publishAt',
  `thumbnail_url` VARCHAR(500) NOT NULL DEFAULT '',
  `duration_iso` VARCHAR(32) NOT NULL DEFAULT '' COMMENT 'contentDetails.duration ISO8601',
  `duration_seconds` INT NOT NULL DEFAULT 0,
  `view_count` BIGINT NOT NULL DEFAULT 0,
  `like_count` BIGINT NOT NULL DEFAULT 0,
  `comment_count` INT NOT NULL DEFAULT 0,
  `favorite_count` BIGINT NOT NULL DEFAULT 0,
  `upload_status` VARCHAR(32) NOT NULL DEFAULT '' COMMENT 'uploaded|processed|rejected|deleted|failed',
  `privacy_status_api` VARCHAR(32) NOT NULL DEFAULT '' COMMENT 'status.privacyStatus 回写',
  `embeddable` TINYINT(1) NOT NULL DEFAULT 1,
  `made_for_kids` TINYINT(1) NOT NULL DEFAULT 0,
  `local_file_path` VARCHAR(500) NOT NULL DEFAULT '' COMMENT '待上传本地文件',
  `mime_type` VARCHAR(128) NOT NULL DEFAULT '',
  `file_size` BIGINT NOT NULL DEFAULT 0,
  `status` VARCHAR(32) NOT NULL DEFAULT 'draft' COMMENT 'draft|uploading|processing|ready|failed|deleted',
  `published_at` DATETIME NULL COMMENT 'snippet.publishedAt',
  `last_synced_at` DATETIME NULL,
  `raw_json` JSON NULL COMMENT '最近一次 API 资源快照',
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_yt_video_platform` (`youtube_video_id`),
  KEY `idx_yt_video_account` (`account_id`),
  KEY `idx_yt_video_owner` (`owner_id`),
  KEY `idx_yt_video_status` (`status`),
  KEY `idx_yt_video_channel` (`channel_id`),
  CONSTRAINT `fk_yt_video_account` FOREIGN KEY (`account_id`) REFERENCES `youtube_accounts` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='YouTube 视频信息';

CREATE TABLE IF NOT EXISTS `youtube_publish_tasks` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `owner_id` INT NOT NULL DEFAULT 0,
  `account_id` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'youtube_accounts.id',
  `video_id` INT UNSIGNED NULL COMMENT '关联 youtube_videos.id（可先建任务后回写）',
  `name` VARCHAR(255) NOT NULL DEFAULT '',
  `status` VARCHAR(32) NOT NULL DEFAULT 'draft' COMMENT 'draft|queued|running|completed|failed|cancelled',
  `title` VARCHAR(255) NOT NULL DEFAULT '',
  `description` MEDIUMTEXT NULL,
  `tags_json` JSON NULL,
  `category_id` VARCHAR(32) NOT NULL DEFAULT '22' COMMENT '默认 People & Blogs',
  `privacy_status` VARCHAR(32) NOT NULL DEFAULT 'private',
  `publish_at` DATETIME NULL,
  `made_for_kids` TINYINT(1) NOT NULL DEFAULT 0,
  `local_file_path` VARCHAR(500) NOT NULL DEFAULT '',
  `mime_type` VARCHAR(128) NOT NULL DEFAULT 'video/*',
  `file_size` BIGINT NOT NULL DEFAULT 0,
  `youtube_video_id` VARCHAR(64) NOT NULL DEFAULT '' COMMENT '发布成功后的平台 ID',
  `progress_percent` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `upload_session_url` VARCHAR(1000) NOT NULL DEFAULT '' COMMENT '可恢复上传会话 URL',
  `error_message` VARCHAR(1000) NOT NULL DEFAULT '',
  `request_json` JSON NULL,
  `response_json` JSON NULL,
  `started_at` DATETIME NULL,
  `finished_at` DATETIME NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_yt_pub_owner` (`owner_id`),
  KEY `idx_yt_pub_account` (`account_id`),
  KEY `idx_yt_pub_video` (`video_id`),
  KEY `idx_yt_pub_status` (`status`),
  KEY `idx_yt_pub_ytvid` (`youtube_video_id`),
  CONSTRAINT `fk_yt_pub_account` FOREIGN KEY (`account_id`) REFERENCES `youtube_accounts` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_yt_pub_video` FOREIGN KEY (`video_id`) REFERENCES `youtube_videos` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='YouTube 视频发布任务';

CREATE TABLE IF NOT EXISTS `youtube_comments` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `owner_id` INT NOT NULL DEFAULT 0,
  `account_id` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '所属频道账号 youtube_accounts.id',
  `video_id` INT UNSIGNED NULL COMMENT '本地 youtube_videos.id',
  `youtube_video_id` VARCHAR(64) NOT NULL DEFAULT '',
  `youtube_comment_id` VARCHAR(128) NOT NULL DEFAULT '' COMMENT 'comment.id',
  `parent_id` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '本地父评论 id，0=顶层',
  `parent_youtube_comment_id` VARCHAR(128) NOT NULL DEFAULT '' COMMENT '回复目标 comment.id / thread 顶层 id',
  `author_channel_id` VARCHAR(64) NOT NULL DEFAULT '',
  `author_display_name` VARCHAR(255) NOT NULL DEFAULT '',
  `author_profile_image_url` VARCHAR(500) NOT NULL DEFAULT '',
  `author_channel_url` VARCHAR(500) NOT NULL DEFAULT '',
  `text_display` MEDIUMTEXT NULL,
  `text_original` MEDIUMTEXT NULL,
  `like_count` INT NOT NULL DEFAULT 0,
  `total_reply_count` INT NOT NULL DEFAULT 0,
  `is_public` TINYINT(1) NOT NULL DEFAULT 1,
  `can_reply` TINYINT(1) NOT NULL DEFAULT 1,
  `moderation_status` VARCHAR(32) NOT NULL DEFAULT '' COMMENT 'published|heldForReview|likelySpam|rejected',
  `published_at` DATETIME NULL,
  `platform_updated_at` DATETIME NULL,
  `pulled_at` DATETIME NULL,
  `raw_json` JSON NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_yt_comment_platform` (`youtube_comment_id`),
  KEY `idx_yt_cmt_account` (`account_id`),
  KEY `idx_yt_cmt_video` (`video_id`),
  KEY `idx_yt_cmt_ytvideo` (`youtube_video_id`),
  KEY `idx_yt_cmt_parent` (`parent_id`),
  KEY `idx_yt_cmt_parent_yt` (`parent_youtube_comment_id`),
  CONSTRAINT `fk_yt_cmt_account` FOREIGN KEY (`account_id`) REFERENCES `youtube_accounts` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_yt_cmt_video` FOREIGN KEY (`video_id`) REFERENCES `youtube_videos` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='YouTube 视频评论（含回复）';

CREATE TABLE IF NOT EXISTS `youtube_comment_reply_tasks` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `owner_id` INT NOT NULL DEFAULT 0,
  `account_id` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'youtube_accounts.id',
  `video_id` INT UNSIGNED NULL COMMENT 'youtube_videos.id',
  `comment_id` INT UNSIGNED NULL COMMENT '要回复的本地 youtube_comments.id',
  `youtube_video_id` VARCHAR(64) NOT NULL DEFAULT '',
  `parent_youtube_comment_id` VARCHAR(128) NOT NULL DEFAULT '' COMMENT 'comments.insert snippet.parentId',
  `reply_text` MEDIUMTEXT NOT NULL COMMENT 'snippet.textOriginal',
  `status` VARCHAR(32) NOT NULL DEFAULT 'draft' COMMENT 'draft|queued|running|completed|failed|cancelled',
  `youtube_reply_comment_id` VARCHAR(128) NOT NULL DEFAULT '' COMMENT '回复成功后的 comment.id',
  `error_message` VARCHAR(1000) NOT NULL DEFAULT '',
  `request_json` JSON NULL,
  `response_json` JSON NULL,
  `started_at` DATETIME NULL,
  `finished_at` DATETIME NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_yt_crt_owner` (`owner_id`),
  KEY `idx_yt_crt_account` (`account_id`),
  KEY `idx_yt_crt_video` (`video_id`),
  KEY `idx_yt_crt_comment` (`comment_id`),
  KEY `idx_yt_crt_status` (`status`),
  CONSTRAINT `fk_yt_crt_account` FOREIGN KEY (`account_id`) REFERENCES `youtube_accounts` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_yt_crt_video` FOREIGN KEY (`video_id`) REFERENCES `youtube_videos` (`id`) ON DELETE SET NULL,
  CONSTRAINT `fk_yt_crt_comment` FOREIGN KEY (`comment_id`) REFERENCES `youtube_comments` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='YouTube 视频评论回复任务';
